using System;
using System.Collections.Generic;
using System.Globalization;
using System.IO;
using System.Linq;
using System.Text;
using System.Web.Script.Serialization;

namespace LayoutStudio.Core
{
    /// <summary>One shared design value (a "token") and the constants it drives in the active theme.</summary>
    public class LookToken
    {
        public string Type;
        public List<string> Constants = new List<string>();
        /// <summary>The theme's value is the token value times this (a TV is read from three metres: bigger radii).</summary>
        public double Scale = 1;
        public double? Max;
        /// <summary>Other constants that follow the first one by an offset; a first value of 0 keeps them at 0 (a focus ring is "corner + 2").</summary>
        public Dictionary<string, double> Extra = new Dictionary<string, double>();
        /// <summary>Other constants that are the first one times a factor (the Play pill is the button corners x 3.33).</summary>
        public Dictionary<string, double> ExtraScale = new Dictionary<string, double>();
        /// <summary>A colour token that also sets a lighter end: the colour mixed this far towards white.</summary>
        public string LightConstant;
        public double LightMix;
    }

    /// <summary>The token to constants table of ONE theme (look-tokens.json, generated by tools/sync_tokens.py).</summary>
    public class LookTable
    {
        public Dictionary<string, LookToken> Tokens = new Dictionary<string, LookToken>();
        /// <summary>Preset groups that exist with the same name and choices in both themes: one choice drives both.</summary>
        public List<string> SharedGroups = new List<string>();

        public static LookTable Parse(string json)
        {
            var table = new LookTable();
            var root = new JavaScriptSerializer().DeserializeObject(json) as IDictionary<string, object>;
            if (root == null) throw new FormatException("the token table is not an object");
            object groups;
            if (root.TryGetValue("sharedGroups", out groups) && groups is System.Collections.IEnumerable)
                foreach (var g in (System.Collections.IEnumerable)groups) table.SharedGroups.Add(Convert.ToString(g, CultureInfo.InvariantCulture));
            object tokens;
            if (root.TryGetValue("tokens", out tokens) && tokens is IDictionary<string, object>)
            {
                foreach (var kv in (IDictionary<string, object>)tokens)
                {
                    var d = kv.Value as IDictionary<string, object>;
                    if (d == null) continue;
                    var t = new LookToken { Type = Str(d, "type") };
                    object list;
                    if (d.TryGetValue("constants", out list) && list is System.Collections.IEnumerable)
                        foreach (var c in (System.Collections.IEnumerable)list) t.Constants.Add(Convert.ToString(c, CultureInfo.InvariantCulture));
                    if (d.ContainsKey("scale")) t.Scale = Num(d["scale"]);
                    if (d.ContainsKey("max")) t.Max = Num(d["max"]);
                    object extra;
                    if (d.TryGetValue("extra", out extra) && extra is IDictionary<string, object>)
                        foreach (var e in (IDictionary<string, object>)extra) t.Extra[e.Key] = Num(e.Value);
                    object extraScale;
                    if (d.TryGetValue("extraScale", out extraScale) && extraScale is IDictionary<string, object>)
                        foreach (var e in (IDictionary<string, object>)extraScale) t.ExtraScale[e.Key] = Num(e.Value);
                    object light;
                    if (d.TryGetValue("light", out light) && light is IDictionary<string, object>)
                    {
                        var l = (IDictionary<string, object>)light;
                        t.LightConstant = Str(l, "constant");
                        t.LightMix = l.ContainsKey("mixWhite") ? Num(l["mixWhite"]) : 0.5;
                    }
                    table.Tokens[kv.Key] = t;
                }
            }
            return table;
        }

        private static string Str(IDictionary<string, object> d, string key) { object v; return d.TryGetValue(key, out v) ? Convert.ToString(v, CultureInfo.InvariantCulture) : null; }
        private static double Num(object v) { return Convert.ToDouble(v, CultureInfo.InvariantCulture); }

        /// <summary>The constant values a token value produces in this theme; null when the token is unknown or the value is not valid for its type.</summary>
        public Dictionary<string, string> ValuesFor(string token, string value)
        {
            LookToken t;
            if (!Tokens.TryGetValue(token, out t) || value == null) return null;
            var result = new Dictionary<string, string>();
            if (t.Type == "Color")
            {
                string argb = NormalizeColor(value);
                if (argb == null) return null;
                foreach (var c in t.Constants) result[c] = argb;
                if (t.LightConstant != null) result[t.LightConstant] = MixWhite(argb, t.LightMix);
                return result;
            }
            double v;
            if (!double.TryParse(value, NumberStyles.Float, CultureInfo.InvariantCulture, out v)) return null;
            v *= t.Scale;
            if (t.Max.HasValue && v > t.Max.Value) v = t.Max.Value;
            bool whole = t.Type == "CornerRadius" || t.Type == "Thickness";
            double main = whole ? Math.Round(v, MidpointRounding.AwayFromZero) : Math.Round(v, 4);
            foreach (var c in t.Constants) result[c] = Format(main, whole);
            foreach (var e in t.Extra)
                result[e.Key] = Format(main == 0 ? 0 : main + e.Value, whole);
            foreach (var e in t.ExtraScale)
                result[e.Key] = Format(whole ? Math.Round(main * e.Value, MidpointRounding.AwayFromZero) : main * e.Value, whole);
            return result;
        }

        private static string Format(double v, bool whole)
        {
            return whole ? ((long)v).ToString(CultureInfo.InvariantCulture) : v.ToString("0.####", CultureInfo.InvariantCulture);
        }

        private static string NormalizeColor(string text)
        {
            string t = text.Trim().TrimStart('#').ToUpperInvariant();
            if (t.Length == 6) t = "FF" + t;
            if (t.Length != 8 || !t.All(Uri.IsHexDigit)) return null;
            return "#" + t;
        }

        private static string MixWhite(string argb, double mix)
        {
            int[] rgb = { Convert.ToInt32(argb.Substring(3, 2), 16), Convert.ToInt32(argb.Substring(5, 2), 16), Convert.ToInt32(argb.Substring(7, 2), 16) };
            for (int i = 0; i < 3; i++) rgb[i] = (int)Math.Round(rgb[i] + (255 - rgb[i]) * mix, MidpointRounding.AwayFromZero);
            return "#" + argb.Substring(1, 2) + rgb[0].ToString("X2") + rgb[1].ToString("X2") + rgb[2].ToString("X2");
        }
    }

    /// <summary>
    /// The Look shared by the Desktop and the Fullscreen theme (look.profile.json in the plugin data folder): the choice of every shared preset
    /// group and the value of any token. Layout stays in each mode's own profile. Authority, lowest first: a preset, a token, the mode's own
    /// override. A damaged file is ignored and never overwritten; a file from a newer version is read-only.
    /// </summary>
    public class Look
    {
        public const int CurrentVersion = 1;

        public int Version = CurrentVersion;
        public Dictionary<string, string> Presets = new Dictionary<string, string>();
        public Dictionary<string, string> Tokens = new Dictionary<string, string>();
        public LookTable Table = new LookTable();
        public string Path;
        public bool ReadOnly;
        public string Warning;
        public bool Dirty { get; private set; }

        public static Look Load(string path, LookTable table)
        {
            var look = new Look { Path = path, Table = table ?? new LookTable() };
            if (path == null || !File.Exists(path)) return look;
            try
            {
                var root = new JavaScriptSerializer().DeserializeObject(File.ReadAllText(path, Encoding.UTF8)) as IDictionary<string, object>;
                if (root == null) throw new FormatException("not an object");
                if (root.ContainsKey("Version")) look.Version = Convert.ToInt32(root["Version"], CultureInfo.InvariantCulture);
                Fill(root, "Presets", look.Presets);
                Fill(root, "Tokens", look.Tokens);
                if (look.Version > CurrentVersion)
                {
                    look.ReadOnly = true;
                    look.Warning = "look.profile.json was written by a newer Layout Studio (version " + look.Version + "); it is read-only";
                }
            }
            catch (Exception ex)
            {
                look.Presets.Clear();
                look.Tokens.Clear();
                look.ReadOnly = true;   // never overwrite what we could not read
                look.Warning = "look.profile.json could not be read (" + ex.Message + "); the shared look is ignored and the file is left untouched";
            }
            return look;
        }

        /// <summary>Reads the file again (another editor instance, the Fullscreen profile edited from the desktop, may have changed it). Nothing is dropped when there is an unsaved change here. True when the values were replaced.</summary>
        public bool ReloadIfClean()
        {
            if (Dirty || Path == null || !File.Exists(Path)) return false;
            var fresh = Load(Path, Table);
            if (fresh.ReadOnly && !ReadOnly) return false;   // unreadable now: keep what we have
            Version = fresh.Version; Presets = fresh.Presets; Tokens = fresh.Tokens; ReadOnly = fresh.ReadOnly; Warning = fresh.Warning;
            return true;
        }

        private static void Fill(IDictionary<string, object> root, string key, Dictionary<string, string> target)
        {
            object value;
            if (!root.TryGetValue(key, out value) || value == null) return;
            var map = value as IDictionary<string, object>;
            if (map == null) throw new FormatException(key + " must be an object");
            foreach (var kv in map) target[kv.Key] = Convert.ToString(kv.Value, CultureInfo.InvariantCulture);
        }

        public bool IsShared(string groupId) { return Table.SharedGroups.Contains(groupId); }

        public bool SetPreset(string groupId, string choiceId)
        {
            if (!IsShared(groupId) || choiceId == null) return false;
            string old;
            if (Presets.TryGetValue(groupId, out old) && old == choiceId) return true;
            Presets[groupId] = choiceId;
            Dirty = true;
            return true;
        }

        /// <summary>Sets a token; false (nothing changed) when the token is unknown or the value is not valid for its type.</summary>
        public bool SetToken(string token, string value)
        {
            if (Table.ValuesFor(token, value) == null) return false;
            string old;
            if (Tokens.TryGetValue(token, out old) && old == value) return true;
            Tokens[token] = value;
            Dirty = true;
            return true;
        }

        /// <summary>Forgets every token value (Reset all): the presets and the theme defaults are all that is left.</summary>
        public void ClearAllTokens()
        {
            if (Tokens.Count == 0) return;
            Tokens.Clear();
            Dirty = true;
        }

        public void ClearToken(string token)
        {
            if (Tokens.Remove(token)) Dirty = true;
        }

        /// <summary>Applies every token to the store; the names that could not be applied are returned.</summary>
        public List<string> ApplyTokens(ConstantStore store)
        {
            var failed = new List<string>();
            foreach (var kv in Tokens)
            {
                var values = Table.ValuesFor(kv.Key, kv.Value);
                if (values == null) { failed.Add(kv.Key); continue; }
                foreach (var v in values)
                {
                    string error;
                    if (!store.TrySet(v.Key, v.Value, out error) && !failed.Contains(kv.Key)) failed.Add(kv.Key);
                }
            }
            return failed;
        }

        /// <summary>The constant values the Look wants in this theme (shared presets, then tokens): what a mode must not save as its own override.</summary>
        public Dictionary<string, string> Wanted(Schema schema, ConstantStore store)
        {
            var wanted = new Dictionary<string, string>();
            foreach (var kv in Presets)
            {
                if (!IsShared(kv.Key)) continue;
                var control = schema.Pages.SelectMany(p => p.Groups).SelectMany(g => g.Controls).FirstOrDefault(c => c.Kind == "preset" && c.Id == kv.Key);
                var choice = control == null ? null : control.Choices.FirstOrDefault(c => c.Id == kv.Value);
                if (choice == null) continue;
                foreach (var c in choice.Constants) wanted[c.Key] = Normal(store, c.Key, c.Value);
            }
            foreach (var kv in Tokens)
            {
                var values = Table.ValuesFor(kv.Key, kv.Value);
                if (values == null) continue;
                foreach (var v in values) wanted[v.Key] = Normal(store, v.Key, v.Value);
            }
            return wanted;
        }

        private static string Normal(ConstantStore store, string key, string raw)
        {
            var def = store.Find(key);
            string normalized, error;
            return def != null && ConstantValue.TryNormalize(def, raw, out normalized, out error) ? normalized : raw;
        }

        /// <summary>Saves like <see cref="SaveIfDirty"/> but never throws: a locked or unwritable file (sync client, antivirus) is logged and retried at the next save. Returns false when it failed.</summary>
        public bool TrySaveIfDirty(Action<string> log)
        {
            try { SaveIfDirty(); return true; }
            catch (Exception ex)
            {
                if (log != null) log("the shared look could not be saved (" + ex.Message + "); it stays unsaved and is retried at the next change");
                try { File.Delete(Path + ".tmp"); } catch (Exception) { }
                return false;
            }
        }

        public void SaveIfDirty()
        {
            if (!Dirty || ReadOnly || Path == null) return;
            var text = new JavaScriptSerializer().Serialize(new Dictionary<string, object> { { "Version", Version }, { "Presets", Presets }, { "Tokens", Tokens } });
            Directory.CreateDirectory(System.IO.Path.GetDirectoryName(Path));
            var temp = Path + ".tmp";
            File.WriteAllText(temp, text, Encoding.UTF8);
            if (File.Exists(Path)) File.Replace(temp, Path, Path + ".bak");
            else File.Move(temp, Path);   // an atomic swap, like the profiles: a power cut leaves the old or the new file, never half of one
            Dirty = false;
        }
    }
}
